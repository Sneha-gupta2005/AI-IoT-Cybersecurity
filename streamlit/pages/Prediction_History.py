# =========================================================
# FILTERS
# =========================================================

st.divider()

st.subheader("🎛️ Filters")

col1, col2 = st.columns(2)

with col1:

    status_filter = st.selectbox(
        "Security Status",
        [
            "All",
            "NORMAL",
            "ATTACK"
        ]
    )

with col2:

    type_options = (
        ["All"] +
        sorted(
            df[
                "predicted_attack_type"
            ]
            .dropna()
            .unique()
            .tolist()
        )
    )

    type_filter = st.selectbox(
        "Attack Type",
        type_options
    )


filtered_df = df.copy()


if status_filter != "All":

    filtered_df = filtered_df[
        filtered_df["attack_status"]
        == status_filter
    ]


if type_filter != "All":

    filtered_df = filtered_df[
        filtered_df[
            "predicted_attack_type"
        ] == type_filter
    ]


