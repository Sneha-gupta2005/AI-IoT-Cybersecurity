from ui import apply_theme
apply_theme()

import streamlit as st
import pandas as pd
import psycopg2
import os
import plotly.express as px
from dotenv import load_dotenv

load_dotenv()

st.set_page_config(
    page_title="Prediction History",
    page_icon="📜",
    layout="wide"
)


# =========================================================
# DATABASE CONNECTION
# =========================================================

def get_connection():

    return psycopg2.connect(
        host=os.getenv("POSTGRES_HOST", "localhost"),
        port=os.getenv("POSTGRES_PORT", "5432"),
        database=os.getenv(
            "POSTGRES_DB",
            "iot_cybersecurity"
        ),
        user=os.getenv(
            "POSTGRES_USER",
            "postgres"
        ),
        password=os.getenv(
            "POSTGRES_PASSWORD"
        )
    )


# =========================================================
# LOAD PREDICTIONS
# =========================================================

@st.cache_data(ttl=5)
def load_predictions():

    conn = get_connection()

    query = """
    SELECT
        id,
        timestamp,
        attack_status,
        attack_probability,
        predicted_attack_type,
        attack_type_confidence,
        src_port,
        dst_port,
        proto,
        service,
        duration,
        src_bytes,
        dst_bytes,
        src_pkts,
        dst_pkts,
        conn_state,
        processed_at
    FROM network_ml_predictions
    ORDER BY timestamp DESC
    """

    df = pd.read_sql(
        query,
        conn
    )

    conn.close()

    df["timestamp"] = pd.to_datetime(
        df["timestamp"],
        errors="coerce"
    )

    return df


# =========================================================
# HEADER
# =========================================================

st.title("📜 Prediction History")

st.caption(
    "Historical network traffic predictions generated by the AI models"
)

st.divider()


# =========================================================
# LOAD DATA
# =========================================================

try:

    df = load_predictions()

except Exception as e:

    st.error(
        "Database connection failed."
    )

    st.code(str(e))

    st.stop()


if df.empty:

    st.info(
        "No predictions have been stored yet."
    )

    st.stop()


# =========================================================
# KPI SECTION
# =========================================================

total_predictions = len(df)

attack_predictions = (
    df["attack_status"] == "ATTACK"
).sum()

normal_predictions = (
    df["attack_status"] == "NORMAL"
).sum()

average_probability = (
    df["attack_probability"].mean()
)


col1, col2, col3, col4 = st.columns(4)

col1.metric(
    "Total Predictions",
    total_predictions
)

col2.metric(
    "Attack Predictions",
    attack_predictions
)

col3.metric(
    "Normal Predictions",
    normal_predictions
)

col4.metric(
    "Average Attack Probability",
    f"{average_probability * 100:.2f}%"
)


st.divider()


